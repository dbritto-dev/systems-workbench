// Runs every lesson's build.mjs and, instead of letting it write a standalone page, collects what it passes to
// writePage(). The Astro site renders pages from that data. Writes, under src/generated/ (not committed):
//
//   lessons/<slug>.json   page data: text (bilingual { en, es } values), figure and panel HTML, experiments, questions
//   live/<slug>.js        the lesson's browser code as an ES module that imports the shared runtime
//   runtime.js            the Anatomy kit's browser helpers + WB (workbench/client.js), shared and cached by every lesson
//   workbench.css         the lesson page stylesheet (kit, theme, page, parts, lit-fill, language)
//   tokens.css            the kit's light/dark colour tokens on :root, for the collection page
//
// and copies the parts gallery to public/. Usage: node tools/export-lessons.mjs [slug ...]
import { mkdirSync, writeFileSync, readFileSync, readdirSync, existsSync, copyFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { join, basename } from "node:path";
import * as k from "../workbench/kit.mjs";
import { THEME_CSS, PAGE_CSS } from "../workbench/page.mjs";
import { PARTS_CSS, LIT_FILL_PAGE_CSS } from "../workbench/parts.mjs";
import { LANG_CSS } from "../workbench/i18n.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const GEN = join(ROOT, "src/generated");
for (const d of ["lessons", "live"]) mkdirSync(join(GEN, d), { recursive: true });

// The shared runtime: the kit's browser helpers, then WB. In the standalone pages these share one script with the
// lesson's code, which uses their names freely; here they become exports the lesson module imports.
const kit = k.kitScript();
const client = readFileSync(join(ROOT, "workbench/client.js"), "utf8")
  .replace("/*@digits*/", readFileSync(join(ROOT, "workbench/digits.mjs"), "utf8").replace(/^export /gm, "").replace(/^/gm, "  ").trimStart());
const NAMES = [...new Set([...kit.matchAll(/^(?:const|let|var|function\*?|class|async function)\s+([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]))].concat("WB");
writeFileSync(join(GEN, "runtime.js"), `// Generated by tools/export-lessons.mjs. Do not edit.\n${kit}\n${client}\nexport { ${NAMES.join(", ")} };\n`);
// Colour tokens for pages outside the lesson template (the collection): the kit's light and dark palettes on :root.
const light = k.ISO_CSS.match(/\.iso\[data-theme="light"\]\{([^}]*)\}/)[1], dark = k.ISO_CSS.match(/\.iso\{([^}]*)\}/)[1];
writeFileSync(join(GEN, "tokens.css"), `/* Generated by tools/export-lessons.mjs. Do not edit. */\n:root{${light};color-scheme:light}\n@media (prefers-color-scheme: dark){:root:not([data-theme="light"]){${dark};color-scheme:dark}}\n:root[data-theme="dark"]{${dark};color-scheme:dark}\n`);
writeFileSync(join(GEN, "workbench.css"), `/* Generated by tools/export-lessons.mjs. Do not edit. */\n${k.ISO_CSS}${THEME_CSS}${PAGE_CSS}${PARTS_CSS}${LIT_FILL_PAGE_CSS}${LANG_CSS}`);

const lessons = JSON.parse(readFileSync(join(ROOT, "workbench/collection/lessons.json"), "utf8"));
const only = new Set(process.argv.slice(2));
let captured = null;
globalThis.__WB_CAPTURE__ = (url, options) => { captured = { url, options }; };
for (const l of lessons) {
  if (only.size && !only.has(l.slug)) continue;
  const build = join(ROOT, "lessons", l.slug, "build.mjs");
  if (!existsSync(build)) throw new Error(`no build.mjs for ${l.slug}`);
  captured = null;
  const t0 = Date.now();
  await import(pathToFileURL(build).href);
  if (!captured) throw new Error(`${l.slug}: build.mjs never called writePage()`);
  const o = captured.options;
  const page = {
    slug: l.slug,
    legacyFile: basename(fileURLToPath(captured.url)),
    title: o.title, eyebrow: o.eyebrow, lede: o.lede,
    machine: { intro: o.machine.intro, figure: o.machine.figure, panel: o.machine.panel },
    predict: { intro: o.predict.intro, experiments: o.predict.experiments.map(({ id, title, change, question, options, why }) => ({ id, title, change, question, options, why })) },
    explain: { intro: o.explain?.intro ?? null, questions: o.explain.questions },
    footer: o.footer ?? null,
    css: o.css ?? "",
    litFill: o.litFill ?? true,
  };
  writeFileSync(join(GEN, "lessons", `${l.slug}.json`), JSON.stringify(page));
  const used = NAMES.filter((n) => new RegExp(`\\b${n.replace(/\$/g, "\\$")}\\b`).test(o.script));
  writeFileSync(join(GEN, "live", `${l.slug}.js`), `// Generated by tools/export-lessons.mjs from lessons/${l.slug}/build.mjs. Do not edit.\nimport { ${used.join(", ")} } from "../runtime.js";\n${o.script}\n`);
  console.log(`exported ${l.slug} (${Date.now() - t0} ms)`);
}
delete globalThis.__WB_CAPTURE__;

mkdirSync(join(ROOT, "public/workbench"), { recursive: true });
copyFileSync(join(ROOT, "workbench/parts-gallery.html"), join(ROOT, "public/workbench/parts-gallery.html"));
console.log(`runtime exports: ${NAMES.length}; lessons: ${readdirSync(join(GEN, "lessons")).length}`);
